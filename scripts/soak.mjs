const children = []; // {name, proc}
function spawnTracked(name, cmd, cmdArgs, opts = {}) {
  const proc = spawn(cmd, cmdArgs, opts);
  children.push({ name, proc });
  log(`started ${name} (pid ${proc.pid})`);
  return proc;
}

async function killTree(entry, signal = "SIGTERM") {
  const { proc, name } = entry;
  if (!proc || proc.killed || proc.exitCode !== null) return;
  try {
    proc.kill(signal);
  } catch {}
  const exited = await Promise.race([
    new Promise((resolve) => proc.once("exit", () => resolve(true))),
    sleep(5000).then(() => false),
  ]);
  if (!exited) {
    try {
      proc.kill("SIGKILL");
    } catch {}
  }
  log(`stopped ${name}`);
}

function getChildPids(pid) {
  try {
    return execSync(`pgrep -P ${pid}`, { stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .split("\n")
      .map((s) => s.trim())
      .filter(Boolean)
      .map(Number);
  } catch {
    return [];
  }
}

