function parseMetricsText(text) {
  const requestsTotal = []; // {labels: {method,path,status,upstream_id,tenant_id}, count}
  const histogramBuckets = new Map(); // le -> count (summed across all series)
  const activeConnections = new Map(); // upstream_id -> count
  const upstreamStatus = new Map(); // upstream_id -> 0|1
  let heapUsedMb = null, arrayBuffersMb = null, externalMb = null, memUsedMb = null;

  const labelRe = /\{([^}]*)\}/;
  function parseLabels(s) {
    const out = {};
    for (const pair of s.split(",")) {
      const m = pair.match(/(\w+)="([^"]*)"/);
      if (m) out[m[1]] = m[2];
    }
    return out;
  }

  for (const line of text.split("\n")) {
    if (line.startsWith("#") || !line.trim()) continue;
    if (line.startsWith("ninja_http_requests_total{")) {
      const lm = line.match(labelRe);
      const valueStr = line.trim().split(" ").pop();
      requestsTotal.push({ labels: lm ? parseLabels(lm[1]) : {}, count: Number(valueStr) });
    } else if (line.startsWith("ninja_http_request_duration_ms_bucket{")) {
      const lm = line.match(labelRe);
      const labels = lm ? parseLabels(lm[1]) : {};
      const valueStr = line.trim().split(" ").pop();
      const le = labels.le;
      histogramBuckets.set(le, (histogramBuckets.get(le) || 0) + Number(valueStr));
    } else if (line.startsWith("ninja_active_connections{")) {
      const lm = line.match(labelRe);
      const labels = lm ? parseLabels(lm[1]) : {};
      const valueStr = line.trim().split(" ").pop();
      activeConnections.set(labels.upstream_id, Number(valueStr));
    } else if (line.startsWith("ninja_upstream_status{")) {
      const lm = line.match(labelRe);
      const labels = lm ? parseLabels(lm[1]) : {};
      const valueStr = line.trim().split(" ").pop();
      upstreamStatus.set(labels.upstream_id, Number(valueStr));
    } else if (line.startsWith("ninja_proxy_heap_used_mb ")) {
      heapUsedMb = Number(line.split(" ")[1]);
    } else if (line.startsWith("ninja_proxy_array_buffers_mb ")) {
      arrayBuffersMb = Number(line.split(" ")[1]);
    } else if (line.startsWith("ninja_proxy_external_mb ")) {
      externalMb = Number(line.split(" ")[1]);
    } else if (line.startsWith("ninja_proxy_memory_used_mb ")) {
      memUsedMb = Number(line.split(" ")[1]);
    }
  }
  return { requestsTotal, histogramBuckets, activeConnections, upstreamStatus, heapUsedMb, arrayBuffersMb, externalMb, memUsedMb };
}

async function scrapeMetrics() {
  const r = await httpRequest("/metrics", { timeout: 5000 });
  return parseMetricsText(r.body);
}

// Approximates the p99 of the aggregate (summed-across-all-series) histogram between two
// scrapes, via standard Prometheus histogram_quantile-style linear interpolation within the
// bucket the 99th percentile falls into.
function estimateP99Ms(prevBuckets, currBuckets) {
  const boundaries = [5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000, Infinity];
  const deltas = boundaries.map((b) => {
    const key = b === Infinity ? "+Inf" : String(b);
    const prev = prevBuckets.get(key) || 0;
    const curr = currBuckets.get(key) || 0;
    return Math.max(0, curr - prev);
  });
  const total = deltas[deltas.length - 1];
  if (total === 0) return 0;
  const target = total * 0.99;
  let lowerBoundary = 0;
  for (let i = 0; i < boundaries.length; i++) {
    if (deltas[i] >= target) {
      const upperBoundary = boundaries[i] === Infinity ? boundaries[i - 1] * 2 : boundaries[i];
      const bucketLow = deltas[i - 1] || 0;
      const bucketHigh = deltas[i];
      if (bucketHigh === bucketLow) return upperBoundary;
      const frac = (target - bucketLow) / (bucketHigh - bucketLow);
      return lowerBoundary + frac * (upperBoundary - lowerBoundary);
    }
    lowerBoundary = boundaries[i];
  }
  return boundaries[boundaries.length - 2];
}

function sumRequestsAndErrors(prevRows, currRows, { excludeUpstream, excludePath } = {}) {
  const key = (r) => `${r.labels.method}|${r.labels.path}|${r.labels.status}|${r.labels.upstream_id}|${r.labels.tenant_id}`;
  const prevMap = new Map(prevRows.map((r) => [key(r), r.count]));
  let totalDelta = 0;
  let errorDelta = 0;
  let excludedTotal = 0;
  let excludedErrors = 0;
  for (const r of currRows) {
    const prevCount = prevMap.get(key(r)) || 0;
    // Counter reset detection (standard Prometheus rate()-style handling): a hot-reload
    // replaces every worker process, zeroing each one's in-memory MetricsRegistry. If the
    // current value is LOWER than the previous scrape's, the counter restarted from zero —
    // the delta is the current value itself, not a negative number clamped away to 0 (which
    // would silently and wrongly report "no traffic" for the whole post-reload interval).
    const delta = r.count < prevCount ? r.count : r.count - prevCount;
    const isError = Number(r.labels.status) >= 500;
    // /dynamic deliberately 503s (upstream_id="none" — no healthy upstream for the route)
    // for most of the run by design: dynamic-upstream is only registered for a short window
    // around the admin register/deregister live op. That's expected test behavior, not a
    // reliability problem, exactly like flapping-backend's own downtime below.
    if ((excludeUpstream && r.labels.upstream_id === excludeUpstream) || (excludePath && r.labels.path === excludePath)) {
      excludedTotal += delta;
      if (isError) excludedErrors += delta;
      continue;
    }
    totalDelta += delta;
    if (isError) errorDelta += delta;
  }
  return { totalDelta, errorDelta, excludedTotal, excludedErrors };
}

