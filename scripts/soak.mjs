function httpRequest(path, { method = "GET", headers = {}, body, port = PROXY_PORT, timeout = 5000 } = {}) {
  return new Promise((resolve, reject) => {
    const req = http.request({ host: "127.0.0.1", port, path, method, headers, timeout }, (res) => {
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks).toString("utf8") }));
    });
    req.on("error", reject);
    req.on("timeout", () => {
      req.destroy();
      reject(new Error("timeout"));
    });
    if (body !== undefined) req.end(body);
    else req.end();
  });
}

async function adminRequest(path, opts = {}) {
  return httpRequest(path, { ...opts, headers: { ...(opts.headers || {}), "x-admin-token": ADMIN_TOKEN } });
}

async function waitForHttp(path, timeoutMs, port = PROXY_PORT) {
  const deadline = now() + timeoutMs;
  while (now() < deadline) {
    try {
      const r = await httpRequest(path, { port, timeout: 1000 });
      if (r.status === 200) return;
    } catch {}
    await sleep(300);
  }
  throw new Error(`${path} on port ${port} never became ready within ${timeoutMs}ms`);
}

