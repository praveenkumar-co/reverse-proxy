// Full label breakdown, accumulated the same reset-aware way, so every metrics-based feature
// proof (429s, 413s, cache hits, pool spread, canary share) survives the hot-reload's mass
// worker replacement instead of only reflecting whatever little traffic landed in the last
// ~1/3 of the run since the reset — a single end-of-run /metrics snapshot undercounts exactly
// like cumulativeRequests/cumulativeErrors would without this.
const cumulativeLabelCounts = new Map(); // "method|path|status|upstream_id|tenant_id" -> count

function accumulateLabelCounts(prevRows, currRows) {
  const key = (r) => `${r.labels.method}|${r.labels.path}|${r.labels.status}|${r.labels.upstream_id}|${r.labels.tenant_id}`;
  const prevMap = new Map(prevRows.map((r) => [key(r), r.count]));
  for (const r of currRows) {
    const prevCount = prevMap.get(key(r)) || 0;
    const delta = r.count < prevCount ? r.count : r.count - prevCount;
    const k = key(r);
    cumulativeLabelCounts.set(k, (cumulativeLabelCounts.get(k) || 0) + delta);
  }
}

function cumulativeSum(predicate) {
  let total = 0;
  for (const [k, count] of cumulativeLabelCounts) {
    const [method, path, status, upstream_id, tenant_id] = k.split("|");
    if (predicate({ method, path, status, upstream_id, tenant_id })) total += count;
  }
  return total;
}
